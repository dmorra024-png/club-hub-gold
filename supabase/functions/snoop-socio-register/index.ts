// SNOOP Socio registration gateway. The member's club email + one-time six-digit
// code is the only verification. This server uses Supabase Auth Admin to create
// an already confirmed Socio-only account AFTER verifying the mailed code.
// Never expose the service key to Cloudflare or the PWA.
import { createClient } from "npm:@supabase/supabase-js@2";

const url = Deno.env.get("SUPABASE_URL");
const key = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
const client = url && key ? createClient(url, key, {
  auth: { autoRefreshToken: false, persistSession: false },
}) : null;
const reply = (status:number, code:string) => new Response(JSON.stringify({ code }), {
  status, headers: {
    "content-type": "application/json; charset=utf-8",
    "cache-control": "no-store",
    "x-content-type-options": "nosniff",
  },
});

Deno.serve(async req => {
  if (req.method !== "POST") return reply(405, "METHOD_NOT_ALLOWED");
  if (!client) return reply(503, "REGISTRATION_UNAVAILABLE");
  if (Number(req.headers.get("content-length") ?? 0) > 1500) return reply(413, "INVALID_INPUT");
  let input: Record<string, unknown>;
  try {
    const raw = await req.text();
    if (raw.length > 1500) return reply(413, "INVALID_INPUT");
    input = JSON.parse(raw);
    if (!input || typeof input !== "object" || Array.isArray(input)) throw Error();
  } catch { return reply(400, "INVALID_INPUT"); }
  const email = typeof input.email === "string" ? input.email.trim().toLowerCase() : "";
  const password = input.password;
  const code = input.code;
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) || email.length > 254 ||
      typeof password !== "string" || password.length < 10 || password.length > 128 ||
      typeof code !== "string" || !/^[0-9]{6}$/.test(code)) {
    return reply(400, "INVALID_INPUT");
  }
  // This RPC is gated to service_role, verifies club/card validity, checks
  // email ownership through the mailed code and counts incorrect attempts.
  let valid: boolean;
  try {
    const { data, error } = await client.rpc("socio_preflight_registration", {
      p_email: email, p_code: code,
    });
    if (error) return reply(503, "REGISTRATION_UNAVAILABLE");
    valid = data === true;
  } catch { return reply(503, "REGISTRATION_UNAVAILABLE"); }
  // Generic error, avoiding user/account existence disclosure.
  if (!valid) return reply(403, "INVALID_OR_EXPIRED_CODE");

  // No signup-confirmation message is generated by Auth Admin; possession of
  // the club-issued email code is the proof of address control.
  const { data: created, error: createError } = await client.auth.admin.createUser({
    email, password, email_confirm: true,
  });
  if (createError || !created?.user?.id) return reply(409, "REGISTRATION_NOT_AVAILABLE");
  const uid = created.user.id;

  try {
    const { data: linked, error } = await client.rpc("socio_finish_registration", {
      p_auth_user_id: uid, p_email: email, p_code: code,
    });
    if (error || linked !== true) {
      await client.auth.admin.deleteUser(uid);
      return reply(409, "INVALID_OR_EXPIRED_CODE");
    }
    return reply(201, "ACTIVATED");
  } catch {
    // Best-effort rollback if the guarded DB claim did not commit.
    await client.auth.admin.deleteUser(uid).catch(() => {});
    return reply(503, "REGISTRATION_UNAVAILABLE");
  }
});
